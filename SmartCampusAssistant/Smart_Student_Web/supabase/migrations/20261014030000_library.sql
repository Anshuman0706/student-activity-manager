create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) > 0),
  author text not null check (char_length(btrim(author)) > 0),
  issued_to uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.books enable row level security;

drop policy if exists "Authenticated users browse books" on public.books;
create policy "Authenticated users browse books"
  on public.books
  for select
  to authenticated
  using (true);

drop policy if exists "Admins publish books" on public.books;
create policy "Admins publish books"
  on public.books
  for insert
  to authenticated
  with check ((select public.is_admin()));

drop policy if exists "Students issue or return their own books" on public.books;
create policy "Students issue or return their own books"
  on public.books
  for update
  to authenticated
  using (issued_to is null or issued_to = (select auth.uid()))
  with check (issued_to is null or issued_to = (select auth.uid()));

drop policy if exists "Admins remove books" on public.books;
create policy "Admins remove books"
  on public.books
  for delete
  to authenticated
  using ((select public.is_admin()));

revoke all on public.books from anon, authenticated;
grant select on public.books to authenticated;
grant insert (title, author) on public.books to authenticated;
grant update (issued_to) on public.books to authenticated;
grant delete on public.books to authenticated;
grant usage, select on sequence public.books_id_seq to authenticated;

notify pgrst, 'reload schema';
